-- 고객 FAQ '예약을 변경하거나 취소할 수 있나요?' 의 답이 기한을 '방문 24시간 전까지' 로 고정 글자로 말했다 (문제 목록 25번, 2026-09-28 — 문구는 코드에서 정함).
-- 실제 기한은 app_settings.cancel_deadline_hours 라 운영자가 바꾸면 FAQ 만 틀린다. FAQ 는 DB 글자 그대로 나가 설정 값을 끼울 수 없으므로 숫자를 뺀다.
-- 기한 시간은 앱이 서버 값으로 보여 준다: 날짜 화면 경고, 잠긴 예약 카드 안내, 정기 회차 취소 시트, 거절 문구(Booking.cancel·reschedule).
update faqs set answer = E'내 예약 탭에서 예약 카드의 예약 변경 · 예약 취소 버튼으로 할 수 있어요. 방문이 가까워 기한이 지나면 버튼 대신 기한 안내가 보이고, 그 뒤에는 고객센터로 문의해주세요.'
 where audience = 'customer' and question = E'예약을 변경하거나 취소할 수 있나요?';
